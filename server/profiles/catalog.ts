import type { ProcessKind, RoastLevel } from "../schema.js";

/**
 * A curated catalog of community espresso profiles for the DE1.
 *
 * Sources (in order of weight):
 *  1. The authors' own notes inside each profile file, as bundled with Decaid
 *     (github.com/decentespresso/decaid, assets/defaultProfiles). These ship on the
 *     tablet, so every title here is normally already installed.
 *  2. Decent's guidance: successful users favour Londinium, D-Flow, Adaptive,
 *     Extractamundo Dos and Allongé; Adaptive v2 is the showroom's most-used
 *     profile; first-espresso guide recommends Adaptive v2 for light/medium and
 *     Londinium for medium/dark (decentespresso.com blog and docs).
 *  3. Community practice, marked as such in `notes`.
 *
 * Titles must match the profile title on the machine exactly.
 */

export type ProfileStyle =
  | "adaptive" // pressure rise then flow follows the puck
  | "blooming" // soak with no flow, then extract
  | "lever" // pressure peak then declining pressure
  | "flat-pressure" // classic 9 bar
  | "flow" // flow-controlled extraction
  | "allonge" // long, high-flow, 4–5:1
  | "turbo" // coarse, fast, high flow
  | "low-contact" // declining temperature, low pressure (Extractamundo family)
  | "scale-driven"; // D-Flow / A-Flow: steps advance on weight

export type Trait = "fruit" | "florals" | "acidity" | "clarity" | "sweetness" | "body" | "chocolate" | "texture" | "forgiving";

export interface CatalogProfile {
  title: string;
  author: string;
  style: ProfileStyle;
  /** Roast levels the author or Decent recommends it for. */
  roasts: RoastLevel[];
  milk: "great" | "ok" | "avoid";
  straight: "great" | "ok";
  /** Tasting traits it brings forward. */
  emphasises: Trait[];
  /** Processes it suits especially well (empty = no preference). */
  processes: ProcessKind[];
  /** Typical recipe from the author's notes. Temperature is the profile's own starting temperature. */
  recipe: { doseG: number; yieldG: number; timeS: [number, number]; tempC: number };
  difficulty: "easy" | "intermediate" | "advanced";
  needsScale: boolean;
  /** Turbo-style profiles want a high-extraction flat-burr grinder. */
  wantsFlatBurrs: boolean;
  /** Community popularity, 1–5 (Decent's guidance and Visualizer usage). */
  popularity: 1 | 2 | 3 | 4 | 5;
  /** One-line description of the cup. */
  character: string;
  /** Dial-in guidance, paraphrasing the author's notes. */
  dialIn: string;
  source: string;
}

