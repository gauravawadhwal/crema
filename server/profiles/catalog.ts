const ORDER: RoastLevel[] = ["light", "medium-light", "medium", "medium-dark", "dark"];
export const roastDistance = (a: RoastLevel, b: RoastLevel) => Math.abs(ORDER.indexOf(a) - ORDER.indexOf(b));

/** Middle of the roast range the profile was written for. */
export function profileRoastCentre(p: CatalogProfile): number {
  const idx = p.roasts.map((r) => ORDER.indexOf(r));
  return idx.reduce((a, b) => a + b, 0) / idx.length;
}

