// Bundles server/engine.ts into skin/engine.js (window.CremaEngine) so the web
// app can rank profiles, build rules recipes and give dial-in advice with no
// Crema server. Re-run after changing anything under server/profiles,
// server/recommend/rules.ts, server/recommend/local.ts or server/shared.
//   node scripts/build-engine.mjs           write skin/engine.js
//   node scripts/build-engine.mjs --check   fail if skin/engine.js is out of date
import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const banner = "/* Generated by scripts/build-engine.mjs from server/engine.ts. Do not edit by hand. */";
const out = buildSync({
  entryPoints: ["server/engine.ts"],
  bundle: true,
  format: "iife",
  globalName: "CremaEngine",
  platform: "browser",
  target: "es2020",
  write: false,
  banner: { js: banner },
});
const code = out.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const current = readFileSync("skin/engine.js", "utf8");
  if (current !== code) {
    console.error("skin/engine.js is out of date. Run: node scripts/build-engine.mjs");
    process.exit(1);
  }
  console.log("skin/engine.js is up to date");
} else {
  writeFileSync("skin/engine.js", code);
  console.log(`skin/engine.js: ${(code.length / 1024).toFixed(0)} KB`);
}
