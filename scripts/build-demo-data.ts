/**
 * Writes skin/demo-data.js: everything the in-browser demo needs, computed by
 * the real server code. Coffees come from samples/beans.json (identified by the
 * real pipeline), AI recipes from samples/recipes.json (real claude-cli runs),
 * and rankings and rules recipes from server/profiles + server/recommend.
 *
 *   npx tsx scripts/build-demo-data.ts
 */
import { readFile, writeFile } from "node:fs/promises";
import { CATALOG } from "../server/profiles/catalog.js";
import { rankProfiles } from "../server/profiles/match.js";
import { rulesRecipe } from "../server/recommend/index.js";
import type { BeanInfo } from "../server/schema.js";

const beans = JSON.parse(await readFile("samples/beans.json", "utf8")).results.filter((r: any) => r.info);
const ai = JSON.parse(await readFile("samples/recipes.json", "utf8")).recipes as Record<string, { recipe: unknown; source: string }>;

// Bag facts only the physical bag knows (roast date, size), plus packshot colours for the demo art.
const BAG: Record<string, { daysAgo: number; weight: number; used: number; shelf: boolean; pack: Record<string, string> }> = {
  "Maple": { daysAgo: 12, weight: 1000, used: 324, shelf: true, pack: { bag: "#2a2522", label: "#d9a25f", ink: "#2a2522", accent: "#2a2522" } },
  "Raspberry Candy": { daysAgo: 21, weight: 250, used: 82, shelf: true, pack: { bag: "#e9b7c3", label: "#fff7f4", ink: "#5b1e33", accent: "#b23a5d" } },
  "Kaliluni AA": { daysAgo: 9, weight: 200, used: 18, shelf: true, pack: { bag: "#f1ece4", label: "#a8372e", ink: "#fff6ee", accent: "#ffd9b8" } },
  "Guji Yabitu Koba G1": { daysAgo: 34, weight: 250, used: 196, shelf: true, pack: { bag: "#f1ece4", label: "#3c5a7a", ink: "#f3efe6", accent: "#f2c27a" } },
  "Compass House Blend": { daysAgo: 15, weight: 250, used: 108, shelf: true, pack: { bag: "#1e3a35", label: "#e8dcc4", ink: "#1e3a35", accent: "#b5582f" } },
  "Kenya Rioki Estate": { daysAgo: 26, weight: 250, used: 140, shelf: true, pack: { bag: "#e8dcc4", label: "#1e3a35", ink: "#f4ecdc", accent: "#e8b45a" } },
  "La Fincona, Honduras, Washed": { daysAgo: 7, weight: 250, used: 0, shelf: false, pack: { bag: "#f1ece4", label: "#5b7a3c", ink: "#f3efe6", accent: "#f6d38a" } },
  "Ethiopia Guji Gogogu": { daysAgo: 6, weight: 250, used: 0, shelf: false, pack: { bag: "#e8dcc4", label: "#6a3c7a", ink: "#f4ecdc", accent: "#f0c1e6" } },
  "Peru Adelino Vega Navara": { daysAgo: 10, weight: 250, used: 0, shelf: false, pack: { bag: "#e8dcc4", label: "#7a4a2c", ink: "#f4ecdc", accent: "#f1c48a" } },
};

const strip = (cands: ReturnType<typeof rankProfiles>) => cands.slice(0, 8).map(({ profile: _p, ...c }) => c);

const out = beans.map((r: { info: BeanInfo }, i: number) => {
  const name = r.info.name.value!;
  const bag = BAG[name];
  if (!bag) throw new Error(`no bag facts for ${name}`);
  const byDrink = Object.fromEntries((["both", "milk", "straight"] as const).map((drink) => {
    const prefs = { drink, hasScale: true, experience: "comfortable" as const };
    const ranking = rankProfiles(r.info, prefs);
    const real = ai[`${name}|${drink}`];
    return [drink, {
      ranking: strip(ranking),
      recipe: real ? real.recipe : rulesRecipe({ bean: r.info, preferences: prefs }, ranking),
      source: real ? `${real.source}, real run` : "rules",
    }];
  }));
  return { id: `b${i + 1}`, batch: `t${i + 1}`, info: { ...r.info, roastDate: { value: null, source: "bag" } }, ...bag, byDrink };
});

const js = `/* Generated by scripts/build-demo-data.ts on ${new Date().toISOString()}. Do not edit by hand. */
window.CREMA_DEMO = ${JSON.stringify({ catalog: CATALOG, beans: out })};
`;
await writeFile("skin/demo-data.js", js);
console.log(`skin/demo-data.js: ${out.length} coffees, ${CATALOG.length} profiles, ${(js.length / 1024).toFixed(0)} KB`);
